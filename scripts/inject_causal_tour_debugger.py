def main() -> int:
    log = ROOT / "app/src/main/java/com/rockmap/app/TourDebugLog.java"
    causality = ROOT / "app/src/main/java/com/rockmap/app/TourDebugCausality.java"
    invariant = ROOT / "app/src/main/java/com/rockmap/app/UiInvariantMonitor.java"
    main_activity = ROOT / "app/src/main/java/com/rockmap/app/MainActivity.java"
    field_activity = ROOT / "app/src/main/java/com/rockmap/app/field/FieldActivity.java"
    research_activity = ROOT / "app/src/main/java/com/rockmap/app/research/ResearchActivity.java"
    research_panel = ROOT / "app/src/main/java/com/rockmap/app/research/ResearchAreaPanelController.java"
    prospecting = ROOT / "app/src/main/java/com/rockmap/app/field/ProspectingAreaCreator.java"
    coach = ROOT / "app/src/main/java/com/rockmap/app/GuidedTourCoach.java"
    mapped = ROOT / "app/src/main/java/com/rockmap/app/map/MapContextCloseController.java"
    field_map = ROOT / "app/src/main/java/com/rockmap/app/field/FieldMapController.java"

    required = [log, causality, invariant, main_activity, field_activity, research_activity,
                research_panel, prospecting, coach, mapped, field_map]
    for path in required:
        if not path.is_file():
            raise RuntimeError(f"required file missing: {path.relative_to(ROOT)}")

    originals = {path: text(path) for path in required}
    build_info = ROOT / "app/src/main/java/com/rockmap/app/TourDebugBuildInfo.java"
    old_build_info = text(build_info) if build_info.is_file() else None
    try:
        generate_build_info()
        patch_tour_debug_log(log)
        patch_causality(causality)
        patch_invariant_monitor(invariant)
        add_touch_override(main_activity, "main", "MainActivity transparent touch tracing")
        add_touch_override(field_activity, "field", "FieldActivity transparent touch tracing")
        add_touch_override(research_activity, "research", "ResearchActivity transparent touch tracing")
        patch_main_tour(main_activity)
        patch_research_panel(research_panel)
        patch_prospecting_prompt(prospecting)
        patch_coach_surface(coach)
        patch_mapped_surface(mapped)
        patch_field_surface(field_map)

        # Scope guard: this pass may mention only diagnostic APIs in the injected markers. It must
        # never introduce direct state mutators as part of debugger instrumentation.
        forbidden_in_debug_classes = [
            ".performClick(", ".setVisibility(", ".bringToFront(", ".requestLayout(",
            ".invalidate(", "GuidedTourState.setStep(", "FieldMapState.set", "MapHudCoordinator.beforeExpand("
        ]
        for path in (causality, ROOT / "app/src/main/java/com/rockmap/app/TourDebugSurfaceAudit.java"):
            content = text(path)
            for token in forbidden_in_debug_classes:
                if token in content:
                    raise RuntimeError(
                        f"debugger scope guard failed: {path.relative_to(ROOT)} contains {token}"
                    )

        print("Causal tour debugger injection complete.")
        print("Scope: observational diagnostics only; no application behavior repair.")
        return 0
    except Exception:
        for path, content in originals.items():
            path.write_text(content, encoding="utf-8")
        if old_build_info is None:
            if build_info.exists():
                build_info.unlink()
        else:
            build_info.write_text(old_build_info, encoding="utf-8")
        print("Causal tour debugger injection rolled back after failure.")
        raise


if __name__ == "__main__":
    raise SystemExit(main())
