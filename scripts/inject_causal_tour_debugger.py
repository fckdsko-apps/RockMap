#!/usr/bin/env python3
"""Causal debugger v1: attribution, watchdogs, surface audits, and transparent touch tracing.

This pass is diagnostic-only. It may add logging calls, transparent dispatchTouchEvent wrappers,
weak View registrations and watchdog observations. It must not change application state, move UI,
invoke app actions, alter return values, or retry/suppress application callbacks.
"""
from pathlib import Path
import os

ROOT = Path(__file__).resolve().parents[1]


def text(path: Path) -> str:
    return path.read_text(encoding="utf-8")


def replace_once(path: Path, marker: str, old: str, new: str, label: str) -> None:
    current = text(path)
    if marker in current:
        print(f"{label}: already present")
        return
    count = current.count(old)
    if count != 1:
        raise RuntimeError(
            f"{label}: expected exactly one match in {path.relative_to(ROOT)}, found {count}"
        )
    path.write_text(current.replace(old, new, 1), encoding="utf-8")
    print(f"{label}: injected")


def ensure_import(path: Path, import_line: str, after_line: str, label: str) -> None:
    current = text(path)
    if import_line in current:
        print(f"{label}: already present")
        return
    if after_line not in current:
        raise RuntimeError(f"{label}: import anchor missing in {path.relative_to(ROOT)}")
    path.write_text(current.replace(after_line, after_line + import_line, 1), encoding="utf-8")
    print(f"{label}: injected")


def generate_build_info() -> None:
    sha = os.environ.get("GITHUB_SHA", "unknown").strip() or "unknown"
    run = os.environ.get("GITHUB_RUN_NUMBER", "local").strip() or "local"
    path = ROOT / "app/src/main/java/com/rockmap/app/TourDebugBuildInfo.java"
